using System.ComponentModel.DataAnnotations;

namespace ExpenseManagement.Api.Infrastructure;

/// <summary>
/// Strongly typed MongoDB configuration bound from the "MongoDb" section.
/// In Docker the values come from environment variables such as MongoDb__ConnectionString.
/// </summary>
public class MongoDbSettings
{
    public const string SectionName = "MongoDb";

    [Required]
    public string ConnectionString { get; set; } = string.Empty;

    [Required]
    public string DatabaseName { get; set; } = string.Empty;

    /// <summary>Insert sample data on startup when the database is empty.</summary>
    public bool SeedData { get; set; }

    /// <summary>
    /// Number of expenses generated by the seeder. A large number makes the difference
    /// between indexed and non-indexed queries visible in explain().
    /// </summary>
    [Range(0, 1_000_000)]
    public int SeedExpenseCount { get; set; } = 50_000;
}
